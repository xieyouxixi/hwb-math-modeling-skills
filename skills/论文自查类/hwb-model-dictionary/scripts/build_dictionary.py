# ---------------------------------------------------------------------------
# 「适用题号」检索提示
#
# ⚠️ 这不是官方题型定义。华为杯 A—F 各题的含义逐届变化，此处只做**检索辅助**：
#    1) 若「适用场景」文本中出现显式题号（如 “华为杯A/D题”“E题常见”），直接采用；
#    2) 否则按领域关键词给一个经验提示（可能多题）；
#    3) 都没有则标为「通用」。
#    当届赛题始终优先，切勿据此预设选题结论。
# ---------------------------------------------------------------------------
_PROB_EXPLICIT = re.compile(r"([A-F](?:\s*/\s*[A-F])*)\s*题")
_PROB_KEYWORDS = (
    ("A", ("芯片", "处理器", "调度", "资源分配", "排布", "硬件", "电路")),
    ("B", ("通信", "网络", "链路", "吞吐", "无线", "WLAN", "组网", "抗干扰")),
    ("C", ("材料", "器件", "磁芯", "损耗", "医学", "诊疗", "脑", "病理", "图像识别", "三维重建")),
    ("D", ("地理", "空间", "时空", "多源", "区域", "路径", "航路", "交通流", "气象", "降水", "碳")),
    ("E", ("故障", "诊断", "轴承", "振动", "传感", "运载", "应急", "信号特征")),
    ("F", ("机理", "力学", "美学", "微分方程", "传热", "结构强度", "量化评价", "脉冲星")),
)


def problem_hint(entry: dict) -> list:
    text = " ".join(str(entry.get(k, "")) for k in ("适用场景", "模型名称", "模型类别"))
    explicit = set()
    for match in _PROB_EXPLICIT.finditer(text):
        explicit.update(re.findall(r"[A-F]", match.group(1)))
    if explicit:
        return sorted(explicit)
    hits = [letter for letter, words in _PROB_KEYWORDS if any(w in text for w in words)]
    return hits if hits else ["通用"]


def build() -> dict:
    data = []
    for index, rec in enumerate(RECORDS, start=1):
        entry = {"序号": index}
        entry.update(rec)
        entry["适用题号"] = problem_hint(entry)
        data.append(entry)

    root = {
        "数据集名称": "HWB 数模模型字典（华为杯研究生赛精简版）",
        "制作方": "HWB 华为杯数模工具组",
        "使用许可": "仅供华为杯（中国研究生数学建模竞赛，CPGMCM）参赛训练与教学非商业使用；"
                    "引用模型须注明原始算法文献与赛题来源；不得用于商业倒卖或再分发牟利。",
        "版权与传播声明": "本字典为精简只读资产，由 HWB 华为杯数模工具组整理生成。"
                          "所有模型条目仅供参赛与教学参考，不构成官方标准；"
                          "正式建模决策请以教材、论文与当届官方文件为准。禁止未经授权的商业传播。"
                          "字段「适用题号」为检索用经验提示，非官方题型定义，题号含义逐届变化，"
                          "须以当届赛题说明为准。",
        "数据": data,
    }
    return root


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT,
                        help="output JSON path (default: assets/model-dictionary.json)")
    args = parser.parse_args()

    root = build()
    out_path: Path = args.out
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as handle:
        json.dump(root, handle, ensure_ascii=False, indent=2)
        handle.write("\n")

    print(f"已生成 {len(root['数据'])} 条模型记录 -> {out_path}")


if __name__ == "__main__":
    main()
